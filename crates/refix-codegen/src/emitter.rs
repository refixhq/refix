use refix_dictionary::Dictionary;

use enums::emit_enum;
pub use error::Error;
use messages::emit_message;
pub use warning::Warning;

/// The result of a successful generation: the generated module, plus any
/// [`Warning`] produced along the way.
#[derive(Debug)]
pub struct Generated {
    pub code: String,
    pub warnings: Vec<Warning>,
}

pub fn generate(dictionary: &Dictionary, source: &str) -> Result<Generated, Error> {
    let mut warnings = Vec::new();

    let header = format!("// @generated by refix-codegen from {source}. Do not edit.");
    let enums: Vec<String> = dictionary
        .fields()
        .iter()
        .filter(|field| !field.values.is_empty())
        .map(emit_enum)
        .collect::<Result<Vec<_>, _>>()?;
    let messages: Vec<String> = dictionary
        .messages()
        .map(|message| emit_message(message, &mut warnings))
        .collect::<Result<Vec<_>, _>>()?;
    let sections = enums
        .into_iter()
        .chain(messages)
        .collect::<Vec<String>>()
        .join("\n");
    let imports = "use refix_message::{InvalidValue, RawMessage, Tag};";
    let code = format!("{header}\n{imports}\n\n{sections}");

    Ok(Generated { code, warnings })
}

#[cfg(test)]
mod tests {
    use super::*;
    use refix_dictionary::{
        Category, DataType, EnumValue, Field, FieldRef, Member, Message, Protocol, Spec, Tag,
        Version,
    };

    fn field(name: &str, tag: u32, data_type: DataType) -> Field {
        Field {
            name: name.to_owned(),
            tag: Tag(tag),
            data_type,
            values: vec![],
        }
    }

    fn spec_of(messages: Vec<Message>, fields: Vec<Field>) -> Spec {
        Spec {
            version: Version {
                protocol: Protocol::Fix,
                major: 4,
                minor: 4,
                service_pack: 0,
            },
            messages,
            components: vec![],
            fields,
        }
    }

    #[test]
    fn generates_a_complete_module() {
        let mut ord_type = field("OrdType", 40, DataType::Other("CHAR".to_owned()));
        ord_type.values = vec![
            EnumValue {
                value: "1".to_owned(),
                description: "MARKET".to_owned(),
            },
            EnumValue {
                value: "2".to_owned(),
                description: "LIMIT".to_owned(),
            },
        ];
        let spec = spec_of(
            vec![Message {
                name: "NewOrderSingle".to_owned(),
                msg_type: "D".to_owned(),
                members: vec![
                    Member::Field(FieldRef {
                        tag: Tag(11),
                        is_required: true,
                    }),
                    Member::Field(FieldRef {
                        tag: Tag(38),
                        is_required: false,
                    }),
                    Member::Field(FieldRef {
                        tag: Tag(44),
                        is_required: false,
                    }),
                    Member::Field(FieldRef {
                        tag: Tag(40),
                        is_required: false,
                    }),
                ],
                category: Category::App,
            }],
            vec![
                field("ClOrdID", 11, DataType::String),
                field("OrderQty", 38, DataType::Int),
                field("Price", 44, DataType::Other("PRICE".to_owned())),
                ord_type,
            ],
        );

        let expected = r#"// @generated by refix-codegen from toy.xml. Do not edit.
use refix_message::{InvalidValue, RawMessage, Tag};

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum OrdType<'a> {
    Market,
    Limit,
    Unknown(&'a [u8]),
}

impl<'a> OrdType<'a> {
    pub fn from_bytes(bytes: &'a [u8]) -> Self {
        match bytes {
            b"1" => Self::Market,
            b"2" => Self::Limit,
            unknown => Self::Unknown(unknown),
        }
    }
}

pub struct NewOrderSingle(RawMessage);

impl NewOrderSingle {
    pub const MSG_TYPE: &[u8] = b"D";

    pub fn from_raw(raw: RawMessage) -> Self {
        Self(raw)
    }

    pub fn raw(&self) -> &RawMessage {
        &self.0
    }

    pub fn cl_ord_id(&self) -> Result<Option<&str>, InvalidValue> {
        self.0.get_str(Tag(11))
    }

    pub fn order_qty(&self) -> Result<Option<i64>, InvalidValue> {
        self.0.get_int(Tag(38))
    }

    pub fn price_raw(&self) -> Option<&[u8]> {
        self.0.get(Tag(44))
    }

    pub fn ord_type(&self) -> Option<OrdType<'_>> {
        self.0.get(Tag(40)).map(OrdType::from_bytes)
    }
}
"#;

        assert_eq!(
            generate(&spec.resolve().unwrap(), "toy.xml").unwrap().code,
            expected
        );
    }

    #[test]
    fn emits_messages_in_spec_order() {
        let spec = spec_of(
            vec![
                Message {
                    name: "Heartbeat".to_owned(),
                    msg_type: "0".to_owned(),
                    members: vec![],
                    category: Category::Admin,
                },
                Message {
                    name: "TestRequest".to_owned(),
                    msg_type: "1".to_owned(),
                    members: vec![],
                    category: Category::Admin,
                },
            ],
            vec![],
        );

        let generated = generate(&spec.resolve().unwrap(), "toy.xml").unwrap();

        let heartbeat = generated.code.find("pub struct Heartbeat").unwrap();
        let test_request = generated.code.find("pub struct TestRequest").unwrap();
        assert!(heartbeat < test_request);
    }
}
