pub fn generate(dictionary: &Dictionary, source: &str) -> Result<Generated, Error> {
    let mut warnings = Vec::new();
    let names = Names::new(dictionary, &mut warnings)?;
    let envelope = Envelope::of(dictionary);

    // The layout is the emitter's own, so formatters leave it alone.
    let header = format!("# @generated by refix codegen from {source}. Do not edit.\n# fmt: off\n");
    let enums: Vec<String> = dictionary
        .fields()
        .iter()
        .filter(|field| Conversion::of(field).is_enum())
        .map(|field| emit_enum(field, &names))
        .collect();
    let shared: Vec<String> = shared_classes(dictionary)
        .into_iter()
        .map(|class| match class {
            Shared::Group(group) => emit_group_class(group, &names),
            Shared::Component(component) => emit_component(component, &names),
        })
        .collect();
    let views: Vec<String> = envelope
        .sections
        .iter()
        .map(|section| emit_view(*section, dictionary, &names))
        .collect();
    let messages: Vec<String> = dictionary
        .messages()
        .map(|message| emit_message(message, &envelope, &names))
        .collect();
    let imports = emit_imports(dictionary, &envelope, !enums.is_empty());
    // isort wants one blank line between the imports and a constant.
    let preamble = format!("{imports}\n{}", emit_dialect(dictionary));
    let sections = [preamble]
        .into_iter()
        .chain(enums)
        .chain(shared)
        .chain(views)
        .chain(messages)
        .chain(emit_dispatch(dictionary))
        .chain(emit_codec(dictionary))
        .collect::<Vec<String>>()
        .join("\n\n");
    let code = format!("{header}\n{sections}");

    warnings.extend(unclaimed_types(dictionary));
    Ok(Generated { code, warnings })
}

/// The import block, naming only what the module uses, with the runtime
/// check ahead of the names imported from `refix`.
fn emit_imports(dictionary: &Dictionary, envelope: &Envelope, has_enums: bool) -> String {
    let has_messages = dictionary.messages().next().is_some();
    let has_classes = has_messages || !envelope.sections.is_empty();

    let mut standard = Vec::new();
    if has_enums {
        standard.push("import enum\n");
    }
    if has_messages {
        standard.push("from typing import TYPE_CHECKING, ClassVar\n");
    } else if has_classes {
        standard.push("from typing import TYPE_CHECKING\n");
    }
    let mut names = vec!["Dialect"];
    if has_messages {
        names.extend(["Codec", "RawMessage"]);
    }
    if has_classes {
        names.push("fields");
    }
    names.sort_unstable();
    let from_refix = format!("from refix import {}\n", names.join(", "));
    let check = emit_runtime_check();
    let blocks = [
        standard,
        vec!["import refix\n"],
        vec![check.as_str()],
        vec![from_refix.as_str()],
    ];
    let blocks: Vec<String> = blocks
        .into_iter()
        .filter(|block| !block.is_empty())
        .map(|block| block.concat())
        .collect();
    blocks.join("\n")
}

